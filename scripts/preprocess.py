## Rewritting of _Atomic into custom RacerF's attribute
def rewrite_atomic(s):
    """This was generated by Claude as a hotfix until _Atomic is properly supported by Frama-C."""
    attr = "__attribute__((__racerf_atomic__))"
    token = re.compile(
        r"""//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*'"""
        r"|\b_Atomic\b",
        re.S,
    )
    out, i = [], 0
    while m := token.search(s, i):
        out.append(s[i : m.start()])
        i = m.end()
        if m.group() != "_Atomic":  # comment or literal
            out.append(m.group())
            continue
        j = i
        while j < len(s) and s[j].isspace():
            j += 1
        if j < len(s) and s[j] == "(":  # _Atomic(T): type specifier
            k, depth = j + 1, 1
            while depth:
                depth += {"(": 1, ")": -1}.get(s[k], 0)
                k += 1
            out.append(f"__typeof__{s[i:j]}({rewrite_atomic(s[j + 1:k - 1])}) {attr}")
            i = k
        else:  # _Atomic: type qualifier
            out.append(attr)
    out.append(s[i:])
    return "".join(out)


